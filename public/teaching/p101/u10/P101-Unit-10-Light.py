import numpy as np
import matplotlib.pyplot as plt

def intensity(power_w, r_m):
    r_m = np.asarray(r_m, dtype=float)
    if not np.isfinite(power_w) or power_w < 0:
        raise ValueError("Power must be finite and non-negative")
    if np.any(~np.isfinite(r_m)) or np.any(r_m <= 0):
        raise ValueError("Distances must be finite and positive")
    return power_w / (4 * np.pi * r_m**2)

r_m = np.linspace(1.0, 5.0, 81)
print("Benchmark at 2 m:", intensity(12.0, 2.0))
print("4 m / 2 m ratio:", intensity(12.0, 4.0) / intensity(12.0, 2.0))
plt.figure()
plt.plot(r_m, intensity(12.0, r_m), label="12 W source")
plt.xlabel("Distance from source / m")
plt.ylabel("Intensity / W m$^{-2}$")
plt.legend()
plt.grid(True)
plt.show()


